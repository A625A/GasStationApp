export type TranslationKey = keyof typeof baseTranslations;

const interpolate = (template: string, vars?: Record<string, string | number>) => {
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(vars[key] ?? ''));
};

export const translate = (key: TranslationKey, language: Language, vars?: Record<string, string | number>) => {
  const template =
    translations[language]?.[key] ?? translations[fallbackLanguage]?.[key] ?? key;
  return interpolate(template, vars);
};

